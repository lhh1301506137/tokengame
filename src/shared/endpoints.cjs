"use strict";

// 本机各服务的约定端口。只有数字与字符串，没有状态、没有逻辑。
//
// 为什么单独一个文件：这些值必须被两侧共享——协调器按它监听，MCP 插件在没配
// TOKENGAME_TABLE_ORIGIN 时按它连。两处各写一遍的坏法很具体：改了一侧，表现是
// 「模型说连不上牌桌，而牌桌明明开着」，读起来像网络问题，实际是两个不一致的数字。
//
// 为什么不从 table-web-host.cjs 里导出：那样 MCP 进程为了一个常量要 require 整个协调器，
// 连同它背后的权威栈。插件进程里不该出现 TableWebHost 这个类——它不构造牌桌是当前
// 的事实，而把类摆在手边会让下一个人觉得构造一个也无妨。host-surface.cjs 能被插件
// require 是同一条理由：那里也只有字符串清单。
//
// 这里只有协调器一个端口，刻意没有核心的。
//
// 核心默认监听随机端口（run-table-core.cjs 的 DEFAULT_PORT = 0），它把地址打出来，
// 人把那一行贴给协调器。那条链路上没有需要两侧各存一份的配置——同一个人在同一个终端里
// 敲两条命令，中间没有跨进程的配置文件会漂。所以给核心也编一个「约定端口」是假的：
// 一个没有任何代码遵守的常量比没有常量更坏，它会让读的人以为 7801 上真的有东西。
//
// 协调器不同：它的地址要进宿主的 MCP 注册项，那是一份人手填、长期存在、与仓库分开升级的
// 配置。约定端口让它只填一次，也让没填的人直接就对。7802 在动态端口范围之外，不会与
// 系统分配的临时端口撞上。
const DEFAULT_TABLE_PORT = 7802;
const DEFAULT_TABLE_ORIGIN = `http://127.0.0.1:${DEFAULT_TABLE_PORT}`;

module.exports = {
  DEFAULT_TABLE_ORIGIN,
  DEFAULT_TABLE_PORT,
};
